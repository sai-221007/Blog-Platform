require('dotenv').config();
const http = require('http');
const app = require('../app');
const { connectDB, disconnectDB } = require('../config/db');
const User = require('../models/User');
const Post = require('../models/Post');
const Comment = require('../models/Comment');

const runTests = async () => {
  console.log('🧪 Starting INKORA Automated QA & API Test Suite...\n');

  await connectDB();

  const server = http.createServer(app);
  await new Promise((resolve) => server.listen(5099, resolve));
  const baseUrl = 'http://localhost:5099';

  let passed = 0;
  let failed = 0;

  const assert = (condition, testName) => {
    if (condition) {
      console.log(`  ✅ PASS: ${testName}`);
      passed++;
    } else {
      console.error(`  ❌ FAIL: ${testName}`);
      failed++;
    }
  };

  try {
    // 1. Health check
    const healthRes = await fetch(`${baseUrl}/api/health`);
    const healthJson = await healthRes.json();
    assert(healthRes.status === 200 && healthJson.product === 'INKORA', 'GET /api/health returns 200 with INKORA status');

    // 2. Register user
    const testEmail = `tester-${Date.now()}@inkora.com`;
    const regRes = await fetch(`${baseUrl}/api/auth/register`, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({
        name: 'Automated Tester',
        email: testEmail,
        password: 'TestPassword123!',
        bio: 'Automated QA suite author',
      }),
    });
    const regJson = await regRes.json();
    assert(regRes.status === 201 && !!regJson.token, 'POST /api/auth/register creates user and returns JWT');
    const token = regJson.token;

    // 3. Login user
    const loginRes = await fetch(`${baseUrl}/api/auth/login`, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({
        email: testEmail,
        password: 'TestPassword123!',
      }),
    });
    const loginJson = await loginRes.json();
    assert(loginRes.status === 200 && !!loginJson.token, 'POST /api/auth/login authenticates with valid credentials');

    // 4. Get Current User (/api/auth/me)
    const meRes = await fetch(`${baseUrl}/api/auth/me`, {
      headers: { Authorization: `Bearer ${token}` },
    });
    const meJson = await meRes.json();
    assert(meRes.status === 200 && meJson.user.email === testEmail, 'GET /api/auth/me returns current user profile');

    // 5. Get Public Posts
    const postsRes = await fetch(`${baseUrl}/api/posts`);
    const postsJson = await postsRes.json();
    assert(postsRes.status === 200 && Array.isArray(postsJson.posts), 'GET /api/posts returns array of published posts');

    // 6. Get Platform Stats
    const statsRes = await fetch(`${baseUrl}/api/posts/editorial/stats`);
    const statsJson = await statsRes.json();
    assert(statsRes.status === 200 && typeof statsJson.stats.totalArticles === 'number', 'GET /api/posts/editorial/stats returns aggregated metrics');

    // 7. Create Article
    const createRes = await fetch(`${baseUrl}/api/posts`, {
      method: 'POST',
      headers: {
        'Content-Type': 'application/json',
        Authorization: `Bearer ${token}`,
      },
      body: JSON.stringify({
        title: `Automated Test Essay ${Date.now()}`,
        summary: 'A test essay generated by automated verification test.',
        content: '## Automated Invariants\n\nVerifying that the content pipeline persists and renders properly without errors.',
        category: 'Technology',
        tags: ['Automated', 'Testing'],
      }),
    });
    const createJson = await createRes.json();
    assert(createRes.status === 201 && !!createJson.post._id, 'POST /api/posts creates new article with author linkage');
    const createdPostId = createJson.post._id;

    // 8. Add Comment
    const commentRes = await fetch(`${baseUrl}/api/posts/${createdPostId}/comments`, {
      method: 'POST',
      headers: {
        'Content-Type': 'application/json',
        Authorization: `Bearer ${token}`,
      },
      body: JSON.stringify({
        content: 'Testing the automated discourse response capability.',
      }),
    });
    const commentJson = await commentRes.json();
    assert(commentRes.status === 201 && !!commentJson.comment._id, 'POST /api/posts/:id/comments adds new comment to post');
    const commentId = commentJson.comment._id;

    // 9. Like Article
    const likeRes = await fetch(`${baseUrl}/api/posts/${createdPostId}/like`, {
      method: 'POST',
      headers: { Authorization: `Bearer ${token}` },
    });
    const likeJson = await likeRes.json();
    assert(likeRes.status === 200 && likeJson.isLiked === true, 'POST /api/posts/:id/like toggles like on article');

    // 10. Update Comment
    const updateCommentRes = await fetch(`${baseUrl}/api/comments/${commentId}`, {
      method: 'PUT',
      headers: {
        'Content-Type': 'application/json',
        Authorization: `Bearer ${token}`,
      },
      body: JSON.stringify({
        content: 'Updated comment content verification.',
      }),
    });
    const updateCommentJson = await updateCommentRes.json();
    assert(updateCommentRes.status === 200 && updateCommentJson.comment.content.includes('Updated'), 'PUT /api/comments/:id updates comment');

    // 11. Delete Post (and cascade)
    const delRes = await fetch(`${baseUrl}/api/posts/${createdPostId}`, {
      method: 'DELETE',
      headers: { Authorization: `Bearer ${token}` },
    });
    assert(delRes.status === 200, 'DELETE /api/posts/:id deletes post and cascades');

    // 12. Newsletter Subscription
    const newsRes = await fetch(`${baseUrl}/api/newsletter/subscribe`, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({ email: `subscriber-${Date.now()}@inkora.com` }),
    });
    assert(newsRes.status === 201, 'POST /api/newsletter/subscribe stores subscriber email');

  } catch (err) {
    console.error('Test execution error:', err);
    failed++;
  } finally {
    server.close();
    await disconnectDB();

    console.log(`\n========================================`);
    console.log(`  Tests Passed: ${passed}`);
    console.log(`  Tests Failed: ${failed}`);
    console.log(`========================================\n`);

    if (failed > 0) process.exit(1);
    process.exit(0);
  }
};

runTests();
